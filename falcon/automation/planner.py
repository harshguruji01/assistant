"""
Task Planning Engine for Falcon.
Decomposes high-level instructions into executable step plans with dependency tracking.
Developed by: HarshGuruJi
"""

from __future__ import annotations

import logging
from typing import Any, Dict, List, Optional
from falcon.automation.workflow import TaskPlan, TaskStep
from falcon.tools.registry import ToolRegistry

logger = logging.getLogger("Falcon.Planner")


class TaskPlanner:
    """Creates structured multi-step execution plans."""

    def __init__(self, tool_registry: ToolRegistry):
        self.tool_registry = tool_registry

    def create_single_tool_plan(self, tool_name: str, arguments: Dict[str, Any], title: str = "") -> TaskPlan:
        """Create a plan consisting of a single tool execution."""
        step = TaskStep(
            title=title or f"Execute {tool_name}",
            tool_name=tool_name,
            arguments=arguments,
        )
        plan = TaskPlan(
            title=title or f"Run {tool_name}",
            description=f"Direct invocation of {tool_name}",
            steps=[step],
        )
        return plan

    def create_document_summary_plan(self, file_path: str, summary_destination: Optional[str] = None) -> TaskPlan:
        """Create a multi-step workflow for document inspection and summary creation."""
        step1 = TaskStep(
            step_id="step_read_doc",
            title=f"Read document: {file_path}",
            tool_name="parse_document",
            arguments={"file_path": file_path, "max_lines": 500},
        )

        steps = [step1]

        if summary_destination:
            step2 = TaskStep(
                step_id="step_save_summary",
                title=f"Save summary to: {summary_destination}",
                tool_name="write_file",
                arguments={"file_path": summary_destination, "content": "Summary generated by Falcon."},
                depends_on=["step_read_doc"],
            )
            steps.append(step2)

        return TaskPlan(
            title="Document Summary Workflow",
            description=f"Analyze document at {file_path} and summarize content.",
            steps=steps,
        )

    def create_system_audit_plan(self) -> TaskPlan:
        """Create a multi-step workflow to assess system health and take a reference screenshot."""
        step1 = TaskStep(
            step_id="step_sys_metrics",
            title="Gather system performance metrics",
            tool_name="get_system_info",
            arguments={},
        )
        step2 = TaskStep(
            step_id="step_screen_capture",
            title="Capture diagnostic screenshot",
            tool_name="take_screenshot",
            arguments={},
            depends_on=["step_sys_metrics"],
        )
        return TaskPlan(
            title="System Audit & Diagnostics",
            description="Collect CPU, RAM, and desktop screenshot for diagnostics.",
            steps=[step1, step2],
        )
